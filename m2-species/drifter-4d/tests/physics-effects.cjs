const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const c=vm.createContext({Math});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../sketch.js'),'utf8')+';globalThis.api={Ecosystem,foodItems,FX};',c);
const {Ecosystem,foodItems,FX}=c.api;
const e=new Ecosystem([],()=>.6);
const a={position:[0,0,0],velocity:[10,0,0],radius:10,mass:1};
const b={position:[18,0,0],velocity:[-5,0,0],radius:10,mass:2};
const momentum=a.velocity[0]*a.mass+b.velocity[0]*b.mass;
assert(e.collide(a,b));
assert(Math.abs(b.position[0]-a.position[0]-20)<1e-8,'overlap resolved');
assert(Math.abs(a.velocity[0]*a.mass+b.velocity[0]*b.mass-momentum)<1e-8,'momentum conserved');
assert(Math.abs(b.velocity[0]-a.velocity[0]-15*FX.restitution)<1e-8,'restitution controls rebound');
assert.equal(e.effects[0].type,'impact');
a.position=[0,0,0];b.position=[19,0,0];a.velocity=[-2,0,0];b.velocity=[2,0,0];
e.collide(a,b);assert.equal(a.velocity[0],-2);assert.equal(b.velocity[0],2,'separating bodies do not bounce again');
a.position=[0,0,0];b.position=[0,0,30];assert.equal(e.collide(a,b),false,'depth separation matters');
b.position=[0,0,0];e.collide(a,b);assert([...a.position,...b.position].every(Number.isFinite),'coincident centers remain finite');
const life=new Ecosystem([foodItems[0]],()=>.6),p=life.prey[0];
p.position=[0,0,0];life.shatter(p,{first:[-1,0,0],second:[0,0,0],distance:1});
assert.equal(life.effects.filter(f=>f.type==='consume').length,1,'one consume effect per capture');
const frozen=JSON.stringify(life);life.update(0);assert.equal(JSON.stringify(life),frozen,'effect age freezes');
for(let i=0;i<Math.ceil((FX.consumeDuration+.1)*60);i++)life.update(1/60,false);
assert.equal(life.effects.length,0,'expired effects removed');
p.respawn=.001;life.update(1/120,false);
assert(p.alive);assert.equal(p.birth,0);assert(life.effects.some(f=>f.type==='birth'));
life.update(.05,false);assert(p.birth>0&&p.birth<FX.birthDuration,'newborn grows over time');
for(let i=0;i<100;i++)life.emit('impact',[0,0,0]);assert.equal(life.effects.length,FX.maxEffects,'effect list bounded');
console.log('PASS: momentum, restitution, overlap, separation, depth, coincident centers, event lifecycle, pause, effect cap.');
